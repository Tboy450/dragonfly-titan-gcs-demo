import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import * as T from '../../dist/vendor/three/three.module.min.js?v=dev';

// Mechanical conversion only; exact original endpoints remain in the builder.
const rows=JSON.parse(await readFile(new URL('candidate-routes.json',import.meta.url),'utf8'));
const accepted=JSON.parse(await readFile(new URL('candidate-checks.json',import.meta.url),'utf8'));
assert.equal(accepted.badPairs.length+accepted.badSurfaces.length+accepted.neighborHits.length,0,'Isolated complete-set acceptance required');
const fittings=JSON.parse(await readFile(new URL('fitting-placements.json',import.meta.url),'utf8'));
assert.equal(createHash('sha256').update(JSON.stringify({rows,fits:fittings})).digest('hex'),accepted.sourceHash,'Candidate changed since acceptance');
assert.deepEqual(rows.map(r=>Number(r.id.split('-').at(-1))).sort((a,b)=>a-b),[4,13,21,22,23,24,25,26]);
const routes={};
for(const row of rows.sort((a,b)=>a.id.localeCompare(b.id))){
 const points=row.points.map(p=>new T.Vector3(...p)),controls=[points[0].toArray()];
 for(let i=1;i<points.length;i++){
  const a=points[i-1],b=points[i],n=Math.ceil(a.distanceTo(b)/.001);
  for(let j=1;j<=n;j++)controls.push(a.clone().lerp(b,j/n).toArray());
 }
 routes[row.id]=controls.slice(1,-1);
}
const serialized='{\n'+Object.entries(routes).map(([id,points])=>
 ' '+JSON.stringify(id)+':[\n'+points.map(p=>'  '+JSON.stringify(p)).join(',\n')+'\n ]').join(',\n')+'\n}';
await writeFile(new URL('../../dist/iem-final-service-routes.mjs',import.meta.url),
 '// Generated by research/iem-final-columns-2026-10-25/write-asset.mjs.\n'+
 '// EST local accommodation; not identified flight circuits or qualified bends.\n'+
 'export const iemFinalServiceRoutes=Object.freeze(Object.fromEntries(\n'+
 ' Object.entries('+serialized+').map(([id,points])=>\n'+
 '  [id,Object.freeze(points.map(point=>Object.freeze(point)))])\n));\n'+
 'export const iemFinalServiceFittings=Object.freeze(Object.fromEntries(\n'+
 ' Object.entries('+JSON.stringify(fittings,null,2)+').map(([id,fit])=>[id,Object.freeze({...fit,\n'+
 ' foot:Object.freeze(fit.foot),lacingFractions:Object.freeze(fit.lacingFractions)})])\n));\n');
console.log('Wrote eight frozen routes with original endpoints supplied by the builder.');
