import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import * as T from '../../dist/vendor/three/three.module.min.js';

// Mechanical conversion of the screened candidate polylines to static asset controls.
const rows=JSON.parse(await readFile(new URL('candidate-routes.json',import.meta.url),'utf8'));
assert.deepEqual(rows.map(row=>Number(row.id.split('-').at(-1))).sort((a,b)=>a-b),[15,16,17,18,19,20,21]);
const routes={};
for(const row of rows.sort((a,b)=>a.id.localeCompare(b.id))){
 const points=row.points.map(p=>new T.Vector3(...p));
 // Preserve the earlier second-column 3 mm gap as well as the shared 2 mm floor.
 if(row.id==='iem-local-lead-15')for(const p of points){
  const taper=T.MathUtils.clamp(Math.min((p.y-.04)/.015,(.10-p.y)/.015,(-.14-p.x)/.01),0,1);
  p.x-=.0016*taper;
 }
 const controls=[points[0].toArray()];
 for(let i=1;i<points.length;i++){
  const a=points[i-1],b=points[i],n=Math.ceil(a.distanceTo(b)/.006);
  for(let j=1;j<=n;j++)controls.push(a.clone().lerp(b,j/n).toArray());
 }
 // The builder supplies the original exact endpoints, not rounded search coordinates.
 routes[row.id]=controls.slice(1,-1);
}
await writeFile(new URL('../../dist/iem-next-service-routes.mjs',import.meta.url),
 '// Generated by research/iem-fifth-sixth-columns-2026-10-25/write-asset.mjs.\n'+
 '// EST accommodation routes only; no flight circuitry or bend qualification.\n'+
 'export const iemNextServiceRoutes=Object.freeze(Object.fromEntries(\n'+
 ' Object.entries('+JSON.stringify(routes,null,2)+').map(([id,points])=>\n'+
 '  [id,Object.freeze(points.map(point=>Object.freeze(point)))])\n'+
 '));\n');
console.log('Wrote seven static routes; original endpoints remain in the builder.');
